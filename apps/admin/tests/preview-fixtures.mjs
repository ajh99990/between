export function previewPlanProvider() {
  const calls = { status: 0, generate: 0, resume: 0, disconnect: 0 };
  let connection = 'unbound';
  return {
    calls,
    async status(_principal, model = DEFAULT_PLAN_MODEL, reasoningEffort = DEFAULT_PLAN_REASONING) {
      calls.status += 1;
      return {
        mode: 'chatgpt-plan', connection, model, reasoningEffort,
        canGenerate: false, authorization: 'required',
        description: connection === 'disconnected' ? '套餐连接已断开。' : '未连接套餐账户。',
        capabilities: { imageInput: false, audioInput: false, voice: false, tts: false, image: false, caption: false },
      };
    },
    async generate() {
      calls.generate += 1;
      throw new Error('隔离预览不连接套餐模型。');
    },
    resume() {
      calls.resume += 1;
      // Clearing a pause cannot grant authorization in this offline preview.
    },
    disconnect() {
      calls.disconnect += 1;
      connection = 'disconnected';
    },
  };
}

