import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import http from 'node:http';
import {startLocalServices} from '../local-start.mjs';
const root=await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(),'between-local-start-')));
const checks=[];let live,blocker,opens=0,closes=0,network=0,tokenReads=0;
const ok=(v,name)=>{assert.ok(v,name);checks.push(name);};
const openCredentials=async()=>{opens++;return {credentials:{load:async()=>({grant_status:'ready',subject:'synthetic',workspace:'synthetic',client_id:'synthetic-client',scope:'resource.invoke chatgpt.tokens.use.direct',expires_at:Date.now()+600000,validated:true,refresh_token:'synthetic-not-a-token'}),getAccessToken:async()=>{tokenReads++;throw Error('Inference forbidden in startup test');}},close:async()=>{closes++;}};};
const options={root,credentialFile:path.join(root,'unused-fixture-path'),appPort:0,servicePort:0,openCredentials,fetchImpl:async()=>{network++;throw Error('External network forbidden');}};
try{
 live=await startLocalServices(options);
 ok(live.state.state==='running'&&live.state.backendEnabled,'First start initializes the explicit local backend');
 ok(live.state.model==='gpt-6.1-sol'&&live.state.reasoningEffort==='medium','First start uses confirmed defaults');
 ok(live.state.http.chat===200&&live.state.http.admin===200&&live.state.http.adminAuthenticated===200,'Both pages and authenticated admin HTTP work');
 ok(live.state.connection==='ready'&&live.state.canGenerate,'Grant metadata marks ready without inference');
 const session=await fetch(live.state.appUrl+'/api/session',{method:'POST',headers:{Origin:live.state.appUrl,'Content-Type':'application/json'},body:'{}'});
 const cookie=session.headers.get('set-cookie').split(';')[0];await session.body.cancel();
 const state=await fetch(live.state.appUrl+'/api/state',{headers:{Cookie:cookie}}),user=await state.json();
 ok(state.status===200&&user.model.reasoningEffort==='medium','Actual user session sees the configured backend');
 const passwordFile=live.state.adminPasswordFile,password=await fs.readFile(passwordFile,'utf8');
 ok(((await fs.stat(passwordFile)).mode&0o777)===0o600,'Admin password stays in a private file');
 await assert.rejects(startLocalServices(options),{code:'EEXIST'});checks.push('Second start cannot take existing ownership');
 ok(opens===1,'Rejected duplicate never opens credentials');
 await live.close();live=null;
 await assert.rejects(fs.stat(path.join(root,'runtime/supervisor.owner')),{code:'ENOENT'});checks.push('Shutdown releases supervisor ownership');
 await assert.rejects(fs.stat(path.join(root,'app-data/engine/.owner')),{code:'ENOENT'});checks.push('Shutdown releases engine ownership');
 const settingsFile=path.join(root,'app-data/settings.json');
 const settings=JSON.parse(await fs.readFile(settingsFile));settings.planBackend.reasoningEffort='high';settings.paused=true;
 await fs.writeFile(settingsFile,JSON.stringify(settings),{mode:0o600});const before=await fs.readFile(settingsFile,'utf8');
 live=await startLocalServices(options);
 ok(live.state.reasoningEffort==='high'&&await fs.readFile(settingsFile,'utf8')===before,'Restart preserves all existing settings byte for byte');
 ok(await fs.readFile(passwordFile,'utf8')===password,'Restart reuses the private admin password');
 await live.close();live=null;
 blocker=http.createServer();await new Promise(r=>blocker.listen(0,'127.0.0.1',r));
 await assert.rejects(startLocalServices({...options,appPort:blocker.address().port}),{code:'EADDRINUSE'});checks.push('Occupied application port fails explicitly');
 await assert.rejects(fs.stat(path.join(root,'runtime/supervisor.owner')),{code:'ENOENT'});
 await assert.rejects(fs.stat(path.join(root,'app-data/engine/.owner')),{code:'ENOENT'});checks.push('Failed startup cleans both locks');
 ok(opens===closes,'Every opened credential owner is closed');
 ok(network===0&&tokenReads===0,'No startup model calls, token refreshes or external network');
 console.log(JSON.stringify({status:'PASS',checks:checks.length,details:checks,realModelCalls:0},null,2));
}finally{await live?.close();if(blocker)await new Promise(r=>blocker.close(r));await fs.rm(root,{recursive:true,force:true});}
